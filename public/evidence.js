/* Evidence pack page. Every dynamic value goes through esc(). */
const $ = s => document.querySelector(s);
const esc = v => String(v ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const dur = s => (s === null || s === undefined ? '—' : s < 90 ? `${Math.round(s)} s` : s < 5400 ? `${Math.round(s / 60)} min` : s < 172800 ? `${(s / 3600).toFixed(1)} h` : `${(s / 86400).toFixed(1)} d`);
const when = t => (t ? new Date(t).toLocaleString() : '—');
const table = (head, rows) => rows.length
  ? `<table><tr>${head.map(h => `<th>${esc(h)}</th>`).join('')}</tr>${rows.map(r => `<tr>${r.map(c => `<td>${c}</td>`).join('')}</tr>`).join('')}</table>`
  : '<div class="meta">None.</div>';
const kpi = (label, value, cls = '') => `<div class="kpi"><span class="meta">${esc(label)}</span><b class="${cls}">${esc(value)}</b></div>`;
let last = null;

function render(e) {
  const r = e.accessRemoval, a = e.auditTrail, adm = e.administrators, id = e.identity, d = e.doors;
  $('#sub').textContent = `${e.tenant.name} · ${new Date(e.period.from).toLocaleDateString()} – ${new Date(e.period.to).toLocaleDateString()} · generated by ${e.generatedBy}`;
  const v = a.verification;
  const sla = r.slaHours || 48;
  const overdue = r.pendingOnSite.filter(p => p.ageHours >= sla);
  $('#out').innerHTML = `
  <h2>1 · Access removal</h2>
  <div class="kpis">
    ${kpi('Remote removals', r.remote.count)}
    ${kpi('Median time to remove', dur(r.remote.p50Sec))}
    ${kpi('Slowest (p95)', dur(r.remote.p95Sec))}
    ${kpi('Needing a site visit', r.pendingOnSite.length, overdue.length ? 'bad' : r.pendingOnSite.length ? 'warn' : 'ok')}
  </div>
  ${r.onSite && r.onSite.count ? `<p class="meta">Completed on site: ${esc(r.onSite.count)} · median ${esc(dur(r.onSite.p50Sec))}.</p>` : ''}
  ${table(['Credential', 'Door', 'Person', 'Waiting since', 'Age'], r.pendingOnSite.map(p => [esc(p.credentialId), esc(p.lockId), esc(p.userId), esc(when(p.since)), `<span class="${p.ageHours >= sla ? 'bad' : ''}">${esc(p.ageHours)} h${p.ageHours >= sla ? ` (over the ${esc(sla)} h target)` : ''}</span>`]))}

  <h2>2 · Administrators</h2>
  ${table(['Name', 'Role', 'Sites', 'Sign-in', 'Last sign-in', 'Flags'], adm.people.map(p => [esc(p.name) + (p.email ? `<div class="meta">${esc(p.email)}</div>` : ''), esc(p.role), esc(p.sites.join(', ')), esc(p.signIn), esc(when(p.lastLoginAt)), p.flags.map(f => `<span class="flag">${esc(f)}</span>`).join('')]))}
  ${adm.bootstrap.length ? `<p class="meta">Configured on the server (env tokens): ${adm.bootstrap.map(b => `${esc(b.name)} (${esc(b.role)})`).join(', ')}.</p>` : ''}
  ${adm.machineIdentities.length ? `<p class="meta">Directory sync connections: ${adm.machineIdentities.map(m => esc(m.name)).join(', ')}.</p>` : ''}
  ${adm.revokedInPeriod.length ? `<p class="meta">Access revoked in period: ${adm.revokedInPeriod.map(m => `${esc(m.name)} (${esc(when(m.revokedAt))})`).join(', ')}.</p>` : ''}

  <h2>3 · Identity</h2>
  <p>Single sign-on: ${id.singleSignOn ? `<b class="ok">on</b> · ${esc(id.singleSignOn.issuer)} · domains ${esc((id.singleSignOn.domains || []).join(', ') || '—')} (DNS-verified: ${esc((id.singleSignOn.verifiedDomains || []).join(', ') || 'none')}) · ${id.singleSignOn.enforced ? '<b class="ok">required for people</b>' : '<b class="warn">optional (tokens also accepted)</b>'}` : '<b class="warn">not configured</b>'}</p>
  <p>Directory sync: ${id.directorySync.connections ? `<b class="ok">on</b> · ${esc(id.directorySync.people)} people (${esc(id.directorySync.deactivated)} deactivated) · ${esc(id.directorySync.mappedGroups)} groups mapped, ${esc(id.directorySync.unmappedGroups)} unmapped` : '<b class="warn">not connected</b>'}</p>

  <h2>4 · Doors</h2>
  <p>${esc(d.total)} doors · ${esc(d.withoutGateway)} without a gateway (removals need a site visit) · lock vendor account: ${d.vendorAccount ? `${esc(d.vendorAccount.status)} (${esc(d.vendorAccount.lockCount)} locks)` : 'shared/demo'}</p>
  ${d.clockChanges && d.clockChanges.length ? `<p class="warn">Upcoming clock changes: ${d.clockChanges.map(c => `${esc(c.site)} ${esc(c.date)} (${c.shiftMinutes > 0 ? '+' : ''}${esc(c.shiftMinutes)} min, ${esc(c.offlineLocks.length)} locks without gateway)`).join(' · ')}</p>` : ''}

  <h2>5 · Four-eyes approvals</h2>
  ${e.fourEyes.sensitiveDoorGroups.length ? `<p>Sensitive door groups (new access needs a second person): ${e.fourEyes.sensitiveDoorGroups.map(g => `${esc(g.name)} (${esc(g.doors)} doors)`).join(', ')}</p>
  <p class="meta">Requests in period: ${Object.entries(e.fourEyes.requestsInPeriod).map(([k, v]) => `${esc(k)} ${esc(v)}`).join(' · ') || 'none'}</p>` : '<p class="warn">No door group is marked sensitive.</p>'}

  <h2>6 · Audit trail</h2>
  <div class="kpis">
    ${kpi('Chain', v.ok ? 'intact' : `broken at #${v.brokenAt}`, v.ok ? 'ok' : 'bad')}
    ${kpi('Entries', v.count)}
    ${kpi('Anchors in period', `${a.anchors.inPeriod} (${a.anchors.deliveredOutside} delivered)`, a.anchors.deliveredOutside ? 'ok' : 'warn')}
    ${kpi('Retention', a.retentionDays ? `${a.retentionDays} days` : 'keep all')}
  </div>
  <p class="meta">Head #${esc(v.head && v.head.seq)} <code>${esc(v.head && v.head.hash)}</code>${v.checkpoint ? ` · starts at retention checkpoint #${esc(v.checkpoint.seq)}` : ''}</p>
  ${a.anchors.last ? `<p class="meta">Last anchor #${esc(a.anchors.last.seq)} at ${esc(when(a.anchors.last.createdAt))} · ${a.anchors.last.signature ? `signed (key ${esc(a.anchors.last.keyId)})` : 'unsigned'} · ${esc(a.anchors.last.deliveredTo ? `${a.anchors.last.deliveredTo}: ${a.anchors.last.deliveryStatus}` : 'not delivered outside AccessX')}</p>` : ''}
  ${a.publicKey ? `<p class="meta">Anchor public key (Ed25519): <code>${esc(a.publicKey.x)}</code></p>` : '<p class="warn">Anchors are not signed on this deployment (AUDIT_SIGNING_KEY not set).</p>'}

  <h2>7 · Control mapping</h2>
  ${table(['Framework', 'Control', 'Title', 'Sections'], e.controls.map(c => [esc(c.framework), `<b>${esc(c.control)}</b>`, esc(c.title), esc(c.evidence.join(', '))]))}
  <div class="disclaimer">${esc(e.disclaimer)} Verify the audit trail independently: export it (Activity → Export) and run <code>npm run audit:verify -- export.json --anchors your-anchors.json --pubkey key.json</code>.</div>`;
}

async function load() {
  $('#out').innerHTML = '';
  const res = await fetch(`/api/reports/evidence?days=${encodeURIComponent($('#days').value)}`, { credentials: 'same-origin' });
  const body = await res.json().catch(() => ({ ok: false, error: `HTTP ${res.status}` }));
  if (!body.ok) {
    $('#sub').textContent = res.status === 401 ? 'Sign in on the main page first.' : res.status === 403 ? 'The evidence pack needs all-site audit access.' : body.error || 'Could not load the evidence pack.';
    return;
  }
  last = body.evidence;
  render(last);
}
$('#days').addEventListener('change', load);
$('#print').addEventListener('click', () => window.print());
$('#json').addEventListener('click', () => {
  if (!last) return;
  const url = URL.createObjectURL(new Blob([JSON.stringify(last, null, 1)], { type: 'application/json' }));
  const a = document.createElement('a');
  a.href = url; a.download = `accessx-evidence-${last.tenant.id}-${last.period.to.slice(0, 10)}.json`;
  document.body.appendChild(a); a.click(); a.remove(); setTimeout(() => URL.revokeObjectURL(url), 1000);
});
load();
